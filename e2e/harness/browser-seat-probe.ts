/**
 * The seat-side half of the browser credential proof
 * (e2e/scenarios/browser-seat-credential.spec.ts).
 *
 * A seat's browser call has to be made BY the seat, with the generation
 * credential the app injected into its own environment. This fixture plants a
 * harness binary that is a probe: the app spawns it as the seat's process, it
 * presents its own `JUNTO_WORK_TOKEN` at the control socket, records what the
 * door answered, and leaves a detached child holding that same environment to
 * call again once the generation has ended.
 *
 * The credential value never leaves the seat. The probe records its shape and
 * the answers, never the value, so no spec code and no window ever reads one.
 */
import { chmod, mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { seededHarnessBinDir } from "./agent-harness-fixture";
import type { Sandbox } from "./sandbox";

/** Where the seat writes what its own calls got. Inside the seat's own home. */
export const browserSeatProbeDir = (home: string): string =>
  join(home, ".junto-e2e", "browser-seat-probe");

export const browserSeatProbePath = (home: string, name: string): string =>
  join(browserSeatProbeDir(home), name);

/** One control answer, as the seat saw it. Never carries the credential. */
export interface SeatProbeAnswer {
  readonly at: number;
  readonly status: number;
  readonly ok: boolean;
  readonly error: { readonly _tag: string; readonly message: string } | null;
  readonly data: unknown;
}

/** What the seat reports about itself before it calls. */
export interface SeatProbeIdentity {
  readonly pid: number;
  readonly nodeRef: string;
  readonly workHome: string;
  readonly home: string;
  readonly argv: ReadonlyArray<string>;
  /** The credential has the shape the core mints, and the seat holds it. */
  readonly credentialShape: boolean;
  readonly tokenPath: string;
  readonly socketPath: string;
}

/**
 * The probe program. Deliberately self-contained (node builtins only): the
 * seat runs it under the app's restricted PATH with only the seat env inject.
 *
 * `seat` mode is the seat's own process. `replay` mode is the detached child,
 * spawned by the seat, inheriting the seat's environment and its credential,
 * in its own session so the stop that ends the generation does not take it.
 */
const PROBE_SOURCE = `#!/usr/bin/env node
// [seat-probe] browser-seat-credential — generated by e2e/harness/browser-seat-probe.ts.
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const http = require("node:http");
const crypto = require("node:crypto");
const cp = require("node:child_process");

const home = process.env.HOME || "";
const dir = path.join(home, ".junto-e2e", "browser-seat-probe");
const socketPath = path.join(home, ".junto", "browser", "control.sock");
const tokenPath = path.join(home, ".junto", "browser", "control.token");
const credential = (process.env.JUNTO_WORK_TOKEN || "").trim();
const mode = process.argv[2] === "replay" ? "replay" : "seat";
const log = path.join(dir, "attempts.ndjson");

fs.mkdirSync(dir, { recursive: true });

const now = () => Date.now();
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

const writeJson = (name, value) => {
  const target = path.join(dir, name);
  fs.writeFileSync(target + ".tmp", JSON.stringify(value, null, 2) + "\\n");
  fs.renameSync(target + ".tmp", target);
};

const note = (value) => {
  try { fs.appendFileSync(log, JSON.stringify(value) + "\\n"); } catch {}
};

const pageNodeIds = (data) =>
  Array.isArray(data) ? data.map((row) => (row && row.nodeId) || null) : null;

/** The seat's own call: its credential from the environment, the door by path. */
const call = () =>
  new Promise((resolve) => {
    let token = "";
    try { token = fs.readFileSync(tokenPath, "utf8").trim(); } catch {}
    const req = http.request(
      {
        socketPath,
        method: "GET",
        path: "/pages",
        headers: {
          "x-junto-token": token,
          "x-junto-seat-credential": credential,
          "x-junto-request-id": crypto.randomUUID(),
        },
        timeout: 15000,
      },
      (res) => {
        const chunks = [];
        res.on("data", (chunk) => chunks.push(chunk));
        res.on("end", () => {
          const raw = Buffer.concat(chunks).toString("utf8");
          let envelope = null;
          try { envelope = JSON.parse(raw); } catch {}
          const ok = Boolean(envelope && envelope.ok === true);
          resolve({
            at: now(),
            status: res.statusCode || 0,
            ok,
            error: envelope && envelope.error ? envelope.error : null,
            data: ok ? envelope.data : null,
          });
        });
      },
    );
    req.on("timeout", () => req.destroy(new Error("control call timed out")));
    req.on("error", (error) =>
      resolve({
        at: now(),
        status: 0,
        ok: false,
        error: { _tag: "socket", message: String((error && error.message) || error) },
        data: null,
      }),
    );
    req.end();
  });

const seat = async () => {
  writeJson("seat.json", {
    pid: process.pid,
    nodeRef: process.env.JUNTO_NODE_REF || "",
    workHome: process.env.JUNTO_WORK_HOME || "",
    home,
    argv: process.argv.slice(2),
    credentialShape: /^junto-seat-[A-Za-z0-9_-]{43}$/.test(credential),
    tokenPath,
    socketPath,
  });
  // The core mints the credential before the spawn and publishes it once the
  // live lease confirms the process, so the seat's first call may race the
  // publish. Keep calling until the door admits this seat.
  const deadline = now() + 30000;
  let admitted = null;
  while (now() < deadline) {
    const answer = await call();
    note({ from: "seat", at: answer.at, status: answer.status, ok: answer.ok, error: answer.error, nodeIds: pageNodeIds(answer.data) });
    if (answer.ok) {
      admitted = answer;
      break;
    }
    await sleep(100);
  }
  writeJson("admitted.json", admitted);
  if (admitted === null) process.exit(1);
  // The seat's process stays up as its TUI. The replay is the same seat's own
  // credential from the same environment, in its own session, so it survives
  // the stop that ends the generation and answers for the call after it.
  const child = cp.spawn(process.execPath, [__filename, "replay"], {
    detached: true,
    stdio: "ignore",
    env: process.env,
  });
  child.unref();
  setInterval(() => {}, 1 << 30);
};

const replay = async () => {
  const deadline = now() + 120000;
  while (now() < deadline) {
    const answer = await call();
    note({ from: "replay", at: answer.at, status: answer.status, ok: answer.ok, error: answer.error, nodeIds: pageNodeIds(answer.data) });
    if (!answer.ok) {
      writeJson("refused.json", answer);
      return;
    }
    await sleep(250);
  }
  writeJson("refused.json", {
    at: now(),
    status: 0,
    ok: false,
    error: { _tag: "timeout", message: "the credential was still admitted after 120 s" },
    data: null,
  });
  process.exitCode = 1;
};

const run = mode === "replay" ? replay : seat;
run().catch((error) => {
  writeJson(mode === "replay" ? "refused.json" : "admitted.json", {
    at: now(),
    status: 0,
    ok: false,
    error: { _tag: "probe", message: String((error && error.stack) || error) },
    data: null,
  });
  process.exit(1);
});
`;

/**
 * Plant the probe as the seat's harness binary, first on the seat's PATH.
 * Call from `afterSeed`, after `seedHarnessInstalls`.
 */
export const installBrowserSeatProbe = async (sandbox: Sandbox): Promise<void> => {
  const dir = browserSeatProbeDir(sandbox.homeDir);
  await mkdir(dir, { recursive: true });
  const program = join(dir, "probe.js");
  await writeFile(program, PROBE_SOURCE, { encoding: "utf8", mode: 0o755 });
  const binDir = seededHarnessBinDir(sandbox);
  await mkdir(binDir, { recursive: true });
  const binary = join(binDir, "codex");
  // Absolute node: the seat's PATH floor has it, and this keeps the probe from
  // depending on how the app resolves `env node`.
  await writeFile(binary, `#!/bin/sh\nexec '${process.execPath}' '${program}' "$@"\n`, "utf8");
  await chmod(binary, 0o755);
};

/** Read a file the seat wrote, or undefined while it is not there yet. */
export const readSeatProbeFile = async <T>(
  home: string,
  name: string,
): Promise<T | undefined> => {
  try {
    return JSON.parse(await readFile(browserSeatProbePath(home, name), "utf8")) as T;
  } catch {
    return undefined;
  }
};
