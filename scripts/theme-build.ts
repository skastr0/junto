#!/usr/bin/env bun
// Generates src/renderer/styles/theme.generated.css from the single token
// source (src/shared/theme/). Dark values land in @theme (Tailwind v4
// registers utilities from them); bright overrides ride on
// html[data-theme="bright"]. Run after editing the source: bun run theme:build
// `bun scripts/theme-build.ts --check` is the gate in bun run verify.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import {
  contrastRatio,
  DARK_RUNTIME,
  semanticTokens,
  TOKEN_NAMES,
  tokenCss,
  themeRuntime,
  FONT_BODY,
  FONT_DISPLAY,
  FONT_MONO,
  LEADING,
  LEGACY_TEXT_SIZES,
  RADIUS,
  TEXT_SIZES,
  TRACKING,
} from "../src/shared/theme";
import { SEMANTIC_BRIGHT_OVERRIDES } from "../src/shared/theme/semantic";

const OUT = resolve(__dirname, "../src/renderer/styles/theme.generated.css");

// The palette the app shipped before tokenization. Dark must keep rendering
// these exact colors; the generator fails loudly if a source edit shifts one.
const LEGACY_DARK_HEX: Record<string, string> = {
  ground: "#0c0b0a",
  raise: "#16130f",
  "raise-2": "#141210",
  inset: "#131110",
  well: "#090807",
  ink: "#ede6da",
  "ink-2": "#c8c0b0",
  // Not legacy any more: brightened on purpose so dim and faint text can be
  // read (see primitives.ts). Pinned here so they cannot drift back.
  dim: "#a59d92",
  faint: "#8d8672",
  amber: "#e8a33d",
  "amber-hi": "#f0d9a8",
  cyan: "#39c6d6",
  violet: "#8b7beb",
  crimson: "#e5484d",
  steel: "#8fa3b0",
  indigo: "#6e7bf2",
  gold: "#d4a94f",
  orange: "#f07438",
  green: "#5fb98e",
};

let failed = false;
for (const [name, hex] of Object.entries(LEGACY_DARK_HEX)) {
  const actual = DARK_RUNTIME[name];
  if (actual !== hex) {
    console.error(`DRIFT: dark ${name} = ${actual}, legacy ${hex}`);
    failed = true;
  }
}
if (failed) {
  console.error(
    "Dark mode must stay pixel-identical. Fix the source or, if the change is deliberate, update LEGACY_DARK_HEX.",
  );
  process.exit(1);
}

const dark = semanticTokens("dark");

const lines: string[] = [
  "/* GENERATED by scripts/theme-build.ts from src/shared/theme/ — do not edit.",
  "   Edit the source, then run `bun run theme:build`. */",
  "",
  // static: every token is emitted even when no utility uses it yet. Tokens
  // are an API: component css read outside this stylesheet must find them.
  "@theme static {",
  "  /* field + elevation ladder, ink ladder, strokes, overlays, scrims,",
  "     hues, color roles. Dark is the default; bright rides data-theme. */",
];
for (const name of TOKEN_NAMES) {
  lines.push(`  --color-${name}: ${tokenCss(name, dark[name]!)};`);
}
lines.push(
  "",
  "  /* house type: mono instrument + condensed display stamp + proportional prose */",
  `  --font-mono: ${FONT_MONO};`,
  `  --font-display: ${FONT_DISPLAY};`,
  `  --font-body: ${FONT_BODY};`,
  "",
  "  /* type scale: a few steps; a legacy value moves to its nearest one */",
);
for (const [name, value] of Object.entries(TEXT_SIZES)) {
  const legacy = LEGACY_TEXT_SIZES.includes(name)
    ? " /* legacy, under review: not for new work */"
    : "";
  lines.push(`  --text-${name}: ${value};${legacy}`);
}
for (const [name, value] of Object.entries(TRACKING)) {
  lines.push(`  --tracking-${name}: ${value};`);
}
for (const [name, value] of Object.entries(LEADING)) {
  lines.push(`  --leading-${name}: ${value};`);
}
lines.push("", "  /* corner radius: sm to xl equal Tailwind's defaults, in px */");
for (const [name, value] of Object.entries(RADIUS)) {
  lines.push(`  --radius-${name}: ${value};`);
}
lines.push(
  "}",
  "",
  'html[data-theme="bright"] {',
  "  color-scheme: light;",
);
for (const [name, value] of Object.entries(SEMANTIC_BRIGHT_OVERRIDES)) {
  lines.push(`  --color-${name}: ${tokenCss(name, value)};`);
}
lines.push("}", "");

// --check (the verify lane) writes nothing: it fails when the committed css
// is not what the source builds, and when the contrast floor below is broken.
const CHECK = process.argv.includes("--check");
const built = lines.join("\n");
if (CHECK) {
  if (readFileSync(OUT, "utf8") !== built) {
    console.error("theme.generated.css is not what src/shared/theme builds. Run `bun run theme:build` and commit the result.");
    process.exit(1);
  }
  console.log("theme.generated.css matches the token source");
} else {
  writeFileSync(OUT, built);
  console.log(`wrote ${OUT}`);
}

// Contrast report. The quiet text tokens are a hard floor: dim and faint are
// what hints, ages, line numbers and crumbs are written in, and they must be
// readable on the two surfaces most text sits on. The rest is informational.
const FLOOR = 4.5;
const HARD: ReadonlyArray<readonly [string, string]> = [
  ["dim", "ground"],
  ["dim", "raise"],
  ["faint", "ground"],
  ["faint", "raise"],
];
console.log("\ncontrast report:");
let unreadable = false;
const report = (mode: "dark" | "bright") => {
  const t = themeRuntime(mode);
  const pairs: Array<[string, string, number]> = [
    ["ink", "ground", 7],
    ["ink-2", "raise", 4.5],
    ...HARD.map(([fg, bg]): [string, string, number] => [fg, bg, FLOOR]),
    ["amber-fg", "ground", 4.5],
    ["cyan-fg", "ground", 4.5],
    ["crimson-fg", "ground", 4.5],
  ];
  for (const [fg, bg, min] of pairs) {
    const ratio = contrastRatio(t[fg]!, t[bg]!);
    const hard = HARD.some(([f, b]) => f === fg && b === bg);
    const mark = ratio >= min ? "ok " : hard ? "FAIL" : "LOW";
    if (ratio < min && hard) unreadable = true;
    console.log(`  ${mode} ${fg}/${bg}: ${ratio.toFixed(2)} (min ${min}) ${mark}`);
  }
};
report("dark");
report("bright");

// Label chips (0.11, 03, C3): the word must clear the floor on its own fill
// over every surface a chip sits on. The fill is the colour's mark at 18%.
const LABEL_NAMES = ["red", "orange", "yellow", "green", "teal", "blue", "purple", "pink"] as const;
const LABEL_FILL_PCT = 18;
const blend = (top: string, under: string, alpha: number): string => {
  const rgb = (hex: string) => [1, 3, 5].map((i) => Number.parseInt(hex.slice(i, i + 2), 16));
  const [a, b] = [rgb(top), rgb(under)];
  return `#${a.map((v, i) => Math.round(v! * alpha + b[i]! * (1 - alpha)).toString(16).padStart(2, "0")).join("")}`;
};
console.log("\nlabel colour report (word on its fill, over each surface):");
for (const mode of ["dark", "bright"] as const) {
  const t = themeRuntime(mode);
  for (const name of LABEL_NAMES) {
    const worst = Math.min(
      ...["ground", "raise", "raise-2", "inset", "well"].map((surface) =>
        contrastRatio(t[`label-${name}-fg`]!, blend(t[`label-${name}`]!, t[surface]!, LABEL_FILL_PCT / 100)),
      ),
    );
    const mark = worst >= FLOOR ? "ok " : "FAIL";
    if (worst < FLOOR) unreadable = true;
    console.log(`  ${mode} label-${name}-fg on fill: ${worst.toFixed(2)} (min ${FLOOR}) ${mark}`);
  }
}

// Chip tones (ui/Chip.tsx): a state tag's word takes the hue's text form on a
// wash of the same hue at 9 percent. The mark form is too dim for the tag's
// 8px words in dark (violet 2.5, steel 2.9, crimson 3.4, green 3.8), so the
// word is the -fg token and this holds it.
const CHIP_TONES = ["amber", "cyan", "violet", "crimson", "steel", "green"] as const;
const CHIP_FILL_PCT = 9;
console.log("\nchip tone report (word on its wash, over each surface):");
for (const mode of ["dark", "bright"] as const) {
  const t = themeRuntime(mode);
  for (const tone of CHIP_TONES) {
    const worst = Math.min(
      ...["ground", "raise", "raise-2", "inset", "well"].map((surface) =>
        contrastRatio(t[`${tone}-fg`]!, blend(t[tone]!, t[surface]!, CHIP_FILL_PCT / 100)),
      ),
    );
    const mark = worst >= FLOOR ? "ok " : "FAIL";
    if (worst < FLOOR) unreadable = true;
    console.log(`  ${mode} ${tone}-fg on wash: ${worst.toFixed(2)} (min ${FLOOR}) ${mark}`);
  }
}
// Threads (0.11.6): the unread count is ground words on a filled amber-fg pill
// at 10px, so it holds the text floor; a selected row is drawn by a full 1px
// amber-fg border on raise-2 and holds the 3 to 1 floor for a non-text mark.
// The mark form, amber, failed the pill in bright at 3.05.
const NON_TEXT_FLOOR = 3;
const THREADS: ReadonlyArray<readonly [string, string, string, number]> = [
  ["unread count, ground on amber-fg", "ground", "amber-fg", FLOOR],
  ["selected row border, amber-fg on raise-2", "amber-fg", "raise-2", NON_TEXT_FLOOR],
];
console.log("\nthreads report:");
for (const mode of ["dark", "bright"] as const) {
  const t = themeRuntime(mode);
  for (const [label, fg, bg, min] of THREADS) {
    const ratio = contrastRatio(t[fg]!, t[bg]!);
    const mark = ratio >= min ? "ok " : "FAIL";
    if (ratio < min) unreadable = true;
    console.log(`  ${mode} ${label}: ${ratio.toFixed(2)} (min ${min}) ${mark}`);
  }
}
if (unreadable) {
  console.error(`\ndim and faint, the label colour words, the chip tone words and the threads unread count must reach ${FLOOR} to 1 in every theme, and the selected thread border ${NON_TEXT_FLOOR} to 1. Raise the token, do not lower the floor.`);
  process.exit(1);
}
