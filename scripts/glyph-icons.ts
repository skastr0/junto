/**
 * Generates src/window/canvas/engine/glyph-nodes.ts — the SVG node data of
 * the lucide icons the GPU glyph atlas draws, lifted verbatim from
 * lucide-react's per-icon modules so the canvas needs no React and no
 * runtime read of node_modules.
 *
 * Run: bun scripts/glyph-icons.ts
 * Regenerate when the glyph map in engine/glyphs.ts or the lucide-react
 * version changes.
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const REPO = join(import.meta.dir, "..");
const ICONS_DIR = join(REPO, "node_modules/lucide-react/dist/esm/icons");
const OUT = join(REPO, "src/window/canvas/engine/glyph-nodes.ts");

// icon file name (kebab) -> export name used inside the generated map key.
// The glyph rasterizer looks nodes up by the kebab name directly.
const NAMES = [
  "activity",
  "archive",
  "circle",
  "circle-check",
  "circle-dashed",
  "circle-dot",
  "circle-pause",
  "circle-slash",
  "clipboard-check",
  "cog",
  "file-text",
  "flag",
  "folder-tree",
  "git-branch",
  "globe",
  "layers",
  "link-2",
  "lock",
  "mail",
  "mail-warning",
  "notebook-pen",
  "package-check",
  "plus",
  "send",
  "square-terminal",
  "stamp",
  "triangle-alert",
  "user",
] as const;

type IconNode = readonly [string, Readonly<Record<string, string>>];

const extract = (file: string, name: string): ReadonlyArray<IconNode> => {
  const src = readFileSync(join(ICONS_DIR, `${file}.js`), "utf8");
  const start = src.indexOf("createLucideIcon(");
  if (start < 0) throw new Error(`${file}.js: no createLucideIcon call`);
  const open = src.indexOf("[", start);
  // The iconNode array ends at the matching "])" — it contains no nested
  // unbalanced brackets in attribute strings, so the first "])" closes it.
  const close = src.indexOf("])", open);
  if (open < 0 || close < 0) throw new Error(`${file}.js: cannot find iconNode array`);
  const literal = src.slice(open, close + 1);
  // The literal is pure data (strings, numbers, arrays, objects). eval is
  // safe here: it is a pinned dependency's shipped source, parsed at build
  // time by a script a developer runs by hand.
  const nodes = eval(literal) as ReadonlyArray<IconNode>;
  if (!Array.isArray(nodes) || nodes.length === 0) throw new Error(`${file}.js: empty iconNode`);
  return nodes;
};

const entries: Array<string> = [];
for (const name of NAMES) {
  if (!readdirSync(ICONS_DIR).includes(`${name}.js`)) {
    throw new Error(`missing icon module: ${name}.js`);
  }
  const nodes = extract(name, name);
  entries.push(`  ${JSON.stringify(name)}: ${JSON.stringify(nodes)},`);
}

const out = `// GENERATED by scripts/glyph-icons.ts — do not edit by hand.
// Lucide icon node data (tag + attributes) for the GPU glyph atlas, lifted
// from lucide-react@${JSON.stringify((JSON.parse(readFileSync(join(REPO, "node_modules/lucide-react/package.json"), "utf8")) as { version: string }).version)}.
// Each icon is stroke-based on a 24x24 viewBox, exactly as lucide-react draws it.

export type GlyphNode = readonly [tag: string, attrs: Readonly<Record<string, string>>];

export const GLYPH_NODES: Readonly<Record<string, ReadonlyArray<GlyphNode>>> = {
${entries.join("\n")}
};
`;

writeFileSync(OUT, out);
console.log(`wrote ${OUT} (${NAMES.length} icons)`);
